// Package systemd writes and controls user units for the daemon and the
// embedded bus. The binary generates the unit from what it knows (its own
// path, the display variables the desktop integration needs) instead of
// asking the person to copy one from deploy/.
package systemd

import (
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
)

// Unit describes a user service.
type Unit struct {
	Name        string
	Description string
	// ExecStart is argv; it is quoted for systemd.
	ExecStart  []string
	After      []string
	Wants      []string
	PartOf     []string
	WantedBy   []string
	Restart    string
	RestartSec int
	// Environment are KEY=value pairs set for the service.
	Environment []string
}

// Result is what InstallUser did.
type Result struct {
	// Path is the unit file written.
	Path string `json:"path"`
	// Installed is true when systemd enabled and started the unit.
	Installed bool `json:"installed"`
	// ImportedEnv reports whether import-environment succeeded.
	ImportedEnv bool `json:"imported_env"`
	// Fallback is what to run by hand when there is no user session.
	Fallback string `json:"fallback,omitempty"`
	// Output is the last systemctl output, for errors.
	Output string `json:"output,omitempty"`
}

// Status is what `systemctl --user` says about a unit.
type Status struct {
	Path    string `json:"path"`
	Exists  bool   `json:"exists"`
	Active  string `json:"active"`
	Enabled string `json:"enabled"`
}

// ErrNoUserSession means systemctl --user cannot be used here: no systemd,
// or a login without a user manager (SSH without lingering, a container).
var ErrNoUserSession = errors.New("no systemd user session")

// Runner runs systemctl. Tests substitute a fake.
type Runner interface {
	Run(ctx context.Context, name string, args ...string) (string, error)
}

// ExecRunner runs real commands.
type ExecRunner struct{}

// Run executes name with args and returns combined output.
func (ExecRunner) Run(ctx context.Context, name string, args ...string) (string, error) {
	out, err := exec.CommandContext(ctx, name, args...).CombinedOutput()
	return strings.TrimSpace(string(out)), err
}

// FakeRunner records calls and answers from a table, for tests.
type FakeRunner struct {
	Calls [][]string
	// Fail maps a systemctl verb (or "systemctl" for all) to an error.
	Fail map[string]error
	// Output maps a verb to what Run returns.
	Output map[string]string
	// Missing makes every call fail as if systemctl were not installed.
	Missing bool
}

// Run records the call and returns the configured answer.
func (f *FakeRunner) Run(_ context.Context, name string, args ...string) (string, error) {
	f.Calls = append(f.Calls, append([]string{name}, args...))
	if f.Missing {
		return "", &exec.Error{Name: name, Err: exec.ErrNotFound}
	}
	verb := ""
	for _, a := range args {
		if !strings.HasPrefix(a, "--") {
			verb = a
			break
		}
	}
	if err, ok := f.Fail[verb]; ok {
		return f.Output[verb], err
	}
	if err, ok := f.Fail[name]; ok {
		return f.Output[verb], err
	}
	return f.Output[verb], nil
}

// UserUnitDir is where user units live.
func UserUnitDir() string {
	if x := os.Getenv("XDG_CONFIG_HOME"); x != "" {
		return filepath.Join(x, "systemd", "user")
	}
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".config", "systemd", "user")
}

// UserUnitPath is the file for a unit name.
func UserUnitPath(name string) string {
	return filepath.Join(UserUnitDir(), name+".service")
}

// Render produces the unit file.
func (u Unit) Render() string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by wormhole; `wormhole service install` or `wormhole serve install` rewrites it.\n")
	b.WriteString("[Unit]\n")
	fmt.Fprintf(&b, "Description=%s\n", u.Description)
	if len(u.After) > 0 {
		fmt.Fprintf(&b, "After=%s\n", strings.Join(u.After, " "))
	}
	if len(u.Wants) > 0 {
		fmt.Fprintf(&b, "Wants=%s\n", strings.Join(u.Wants, " "))
	}
	if len(u.PartOf) > 0 {
		fmt.Fprintf(&b, "PartOf=%s\n", strings.Join(u.PartOf, " "))
	}
	b.WriteString("\n[Service]\n")
	fmt.Fprintf(&b, "ExecStart=%s\n", quoteArgv(u.ExecStart))
	for _, e := range u.Environment {
		fmt.Fprintf(&b, "Environment=%s\n", quoteArg(e))
	}
	if u.Restart != "" {
		fmt.Fprintf(&b, "Restart=%s\n", u.Restart)
	}
	if u.RestartSec > 0 {
		fmt.Fprintf(&b, "RestartSec=%d\n", u.RestartSec)
	}
	if len(u.WantedBy) > 0 {
		b.WriteString("\n[Install]\n")
		fmt.Fprintf(&b, "WantedBy=%s\n", strings.Join(u.WantedBy, " "))
	}
	return b.String()
}

// quoteArgv renders argv the way systemd's ExecStart parses it.
func quoteArgv(argv []string) string {
	parts := make([]string, len(argv))
	for i, a := range argv {
		parts[i] = quoteArg(a)
	}
	return strings.Join(parts, " ")
}

// quoteArg double-quotes an argument when it needs it.
func quoteArg(a string) string {
	if a != "" && !strings.ContainsAny(a, " \t\"'\\$;%") {
		return a
	}
	return strconv.Quote(a)
}

// InstallUser writes the unit, reloads the user manager, imports the
// environment variables the desktop integration needs and enables and
// starts the unit. Without a user session it writes the file, returns
// ErrNoUserSession and fills Result.Fallback.
func InstallUser(ctx context.Context, r Runner, u Unit, importEnv []string, fallback string) (Result, error) {
	res := Result{Path: UserUnitPath(u.Name), Fallback: fallback}
	if err := os.MkdirAll(filepath.Dir(res.Path), 0o755); err != nil {
		return res, err
	}
	if err := os.WriteFile(res.Path, []byte(u.Render()), 0o644); err != nil {
		return res, err
	}
	out, err := r.Run(ctx, "systemctl", "--user", "daemon-reload")
	if err != nil {
		res.Output = out
		return res, noSession(err, out)
	}
	if len(importEnv) > 0 {
		if _, err := r.Run(ctx, "systemctl", append([]string{"--user", "import-environment"}, importEnv...)...); err == nil {
			res.ImportedEnv = true
		}
	}
	out, err = r.Run(ctx, "systemctl", "--user", "enable", "--now", u.Name+".service")
	if err != nil {
		res.Output = out
		return res, noSession(err, out)
	}
	res.Installed = true
	res.Fallback = ""
	return res, nil
}

// noSession maps a systemctl failure to ErrNoUserSession when that is
// what it means.
func noSession(err error, out string) error {
	var ee *exec.Error
	if errors.As(err, &ee) && errors.Is(ee.Err, exec.ErrNotFound) {
		return fmt.Errorf("%w: systemctl is not installed", ErrNoUserSession)
	}
	low := strings.ToLower(out)
	if strings.Contains(low, "failed to connect to bus") || strings.Contains(low, "no such file or directory") || strings.Contains(low, "not been booted with systemd") || strings.Contains(low, "xdg_runtime_dir") {
		return fmt.Errorf("%w: %s", ErrNoUserSession, out)
	}
	if out == "" {
		return err
	}
	return fmt.Errorf("%v: %s", err, out)
}

// Query reports whether the unit file exists and what systemd says.
func Query(ctx context.Context, r Runner, name string) Status {
	st := Status{Path: UserUnitPath(name)}
	if _, err := os.Stat(st.Path); err == nil {
		st.Exists = true
	}
	st.Active, _ = r.Run(ctx, "systemctl", "--user", "is-active", name+".service")
	st.Enabled, _ = r.Run(ctx, "systemctl", "--user", "is-enabled", name+".service")
	if st.Active == "" {
		st.Active = "unknown"
	}
	if st.Enabled == "" {
		st.Enabled = "unknown"
	}
	return st
}

// Uninstall stops and disables the unit and removes its file.
func Uninstall(ctx context.Context, r Runner, name string) (string, error) {
	path := UserUnitPath(name)
	_, _ = r.Run(ctx, "systemctl", "--user", "disable", "--now", name+".service")
	if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return path, err
	}
	_, _ = r.Run(ctx, "systemctl", "--user", "daemon-reload")
	return path, nil
}

// Restart restarts a unit, ignoring failures when it is not running.
func Restart(ctx context.Context, r Runner, name string) error {
	out, err := r.Run(ctx, "systemctl", "--user", "restart", name+".service")
	if err != nil {
		return noSession(err, out)
	}
	return nil
}
